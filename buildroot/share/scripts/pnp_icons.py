# pnp_icons.py
#
# Draw the Pick and Place status screen icons and export them as
# 64x64 4-bit greyscale C++ arrays for TFT_COLOR_UI.
#
# Pixel values: 8 = background ... 15 = icon color (see TFT_Queue::add_image)
#
# Usage: pnp_icons.py OUTPUT_DIR [PREVIEW.png]
